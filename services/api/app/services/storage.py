import re
import shutil
import tempfile
from pathlib import Path, PurePosixPath

from app.config import get_settings


class InvalidStorageKey(ValueError):
    pass


class LocalStorage:
    """Local filesystem driver with strict key containment.

    Keys are always relative POSIX paths. They are generated by the server, never
    taken from a filename supplied by the internet.
    """

    def __init__(self, root: Path) -> None:
        self.root = root.expanduser().resolve()

    def _resolve(self, key: str) -> Path:
        if not key or "\x00" in key:
            raise InvalidStorageKey("storage key tidak valid")
        normalized = key.replace("\\", "/")
        if re.match(r"^[A-Za-z]:", normalized):
            raise InvalidStorageKey("storage key tidak boleh memakai drive letter")
        pure = PurePosixPath(normalized)
        if pure.is_absolute() or any(part in ("..", ".") for part in pure.parts):
            raise InvalidStorageKey("storage key tidak boleh keluar dari root")
        candidate = (self.root / Path(*pure.parts)).resolve()
        if candidate != self.root and self.root not in candidate.parents:
            raise InvalidStorageKey("storage key tidak boleh keluar dari root")
        if candidate == self.root:
            raise InvalidStorageKey("storage key harus menunjuk ke file")
        return candidate

    def save_bytes(self, key: str, data: bytes) -> Path:
        path = self._resolve(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a sibling temp file and rename so readers never see a half file.
        with tempfile.NamedTemporaryFile(
            dir=path.parent, prefix=f".{path.name}.", suffix=".part", delete=False
        ) as handle:
            handle.write(data)
            handle.flush()
            temp_path = Path(handle.name)
        temp_path.replace(path)
        return path

    def path_for(self, key: str) -> Path:
        return self._resolve(key)

    def move_in(self, key: str, source: Path) -> Path:
        path = self._resolve(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(source), path)
        return path

    def read_bytes(self, key: str) -> bytes:
        return self._resolve(key).read_bytes()

    def exists(self, key: str) -> bool:
        return self._resolve(key).is_file()

    def size(self, key: str) -> int:
        return self._resolve(key).stat().st_size

    def delete(self, key: str) -> None:
        path = self._resolve(key)
        path.unlink(missing_ok=True)

    def ready(self) -> bool:
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=self.root, prefix=".health-", delete=True):
                return True
        except OSError:
            return False


_storage: LocalStorage | None = None


def get_storage() -> LocalStorage:
    global _storage
    if _storage is None:
        _storage = LocalStorage(get_settings().media_path)
    return _storage
